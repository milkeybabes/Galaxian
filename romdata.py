class _Rom:
    """Read-only view of the lifted ROM regions, addressed like the original."""
    def __init__(self):
        self._map = {}
        for base, data in REGIONS.items():
            for i, v in enumerate(data):
                self._map[base + i] = v

    def __getitem__(self, addr):
        return self._map[addr]

    def word(self, addr):
        return self._map[addr] | (self._map[addr + 1] << 8)


ROM = _Rom()
